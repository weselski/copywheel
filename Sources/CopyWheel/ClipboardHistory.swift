import AppKit

/// Merkt sich die letzten Texte der Zwischenablage – auch solche, die in
/// anderen Apps mit ⌘C kopiert wurden. macOS meldet Änderungen nicht, daher
/// wird der changeCount des Pasteboards regelmäßig abgefragt.
/// Der Verlauf liegt nur im Speicher und wird nie auf die Platte geschrieben.
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let limit = 10
    static let enabledKey = "historyEnabled"

    @Published private(set) var entries: [String] = []

    /// Passwortmanager & Co. markieren Einträge, die in keinem Verlauf
    /// landen sollen (siehe nspasteboard.org).
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        concealedType,
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount = -1
    private var timer: Timer?

    var isEnabled: Bool { UserDefaults.standard.bool(forKey: Self.enabledKey) }

    private init() {
        UserDefaults.standard.register(defaults: [Self.enabledKey: true])
    }

    /// Startet bzw. stoppt die Überwachung passend zur Einstellung.
    /// Ausschalten leert den Verlauf.
    func updateMonitoring() {
        if isEnabled {
            guard timer == nil else { return }
            poll()
            let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            timer?.invalidate()
            timer = nil
            entries = []
        }
    }

    func clear() {
        entries = []
    }

    /// Legt Text in die Zwischenablage. Geheimnisse werden als "concealed"
    /// markiert und nicht in den Verlauf übernommen.
    func copy(_ text: String, isSecret: Bool = false, remember: Bool = false) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        if isSecret {
            pasteboard.setData(Data(), forType: Self.concealedType)
        }
        lastChangeCount = pasteboard.changeCount
        if remember && !isSecret && isEnabled {
            add(text)
        }
    }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }
        add(text)
    }

    private func add(_ text: String) {
        entries.removeAll { $0 == text }
        entries.insert(text, at: 0)
        if entries.count > Self.limit {
            entries.removeLast(entries.count - Self.limit)
        }
    }
}
